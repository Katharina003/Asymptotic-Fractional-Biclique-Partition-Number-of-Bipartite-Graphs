/*
set up constraints and objective of qubo
*/
void QuboEdgeorbits::setUpQubo(Biclique& maxBiclique, vector<double>& dualSolutions, DominoGraph& dominoGraph, GRBModel& qubo, vector<GRBVar>& x, int timeLimit) {
    cout << "setting up qubo problem" << endl;

    vector<CondensedNode> top = maxBiclique.getTop();
    vector<CondensedNode> bot = maxBiclique.getBot();

    //top nodes are not compressed, bottom nodes can be compressed
    //find all combinations of top and bottom nodes
    vector<tuple<CondensedNode, EdgeOrbit, int>> z;
    for (CondensedNode tNode : top) {
        for (CondensedNode bNode : bot) {
            z.push_back({ tNode, EdgeOrbit::topBottomToEdge(tNode,bNode),bNode.getNumOccurences() });
        }
    }
    sort(z.begin(), z.end());
    // addup entries of the same kind
    vector<tuple<CondensedNode, EdgeOrbit, int>> result;
    result.push_back(z[0]);
    for (int i = 1;i < z.size();++i) {
        int lastIndex = result.size() - 1;
        //when it is a node of the same edge
        if (get<0>(result[lastIndex]).getName() == get<0>(z[i]).getName()
            && get<1>(result[lastIndex]) == get<1>(z[i])) {
            result[lastIndex] = {get<0>(result[lastIndex]),get<1>(result[lastIndex]),get<2>(result[lastIndex]) + get<2>(z[i])};
        }
        else {
            result.push_back(z[i]);
        }
    }
    z = result;

    vector<int> topDecompressed;
    for (CondensedNode n : top) {
        for (int i = 0;i < n.getNumOccurences();++i) {
            topDecompressed.push_back(n.getName());
        }
    }

    int topNodeIndex = 0;
    int subtract = 0;
    CondensedNode currentNode = get<0>(z[0]);
    vector<tuple<int, CondensedNode, EdgeOrbit, int>> zDecompressed; //first entry is index of topnode in x
    for (int j = 0;j < z.size();++j) {
        auto& tup = z[j];
        if (get<0>(tup) == currentNode) topNodeIndex -= subtract;
        else {
            currentNode = get<0>(tup);
        }

        for (int i = 0;i < get<0>(tup).getNumOccurences();++i) {
            zDecompressed.push_back({topNodeIndex,get<0>(tup), get<1>(tup), get<2>(tup)});
            topNodeIndex++;
        }
        subtract = get<0>(tup).getNumOccurences();
    }

    x = vector<GRBVar>(topDecompressed.size() + bot.size()+zDecompressed.size());

    for (int i = 0; i < topDecompressed.size(); ++i) {
        x[i] = qubo.addVar(0.0, 1.0, 0.0, GRB_BINARY, "x_" + to_string(i));
    }
    for (int i = topDecompressed.size(); i < topDecompressed.size() + bot.size(); ++i) {
        x[i] = qubo.addVar(0.0, bot[i - topDecompressed.size()].getNumOccurences(), 0.0, GRB_INTEGER, "x_" + to_string(i));
    }
    //zDecompressed is a value between 0 and number of used nodes at the i-th position that is generated by the edge equiv class.
    for (int i = topDecompressed.size() + bot.size(); i < x.size();++i) {
        x[i] = qubo.addVar(0.0, get<3>(zDecompressed[i-topDecompressed.size()-bot.size()]), 0.0, GRB_INTEGER, "x_" + to_string(i));
    }

    GRBLinExpr obj = 0;

    for (int i = 0;i < zDecompressed.size();++i) {
        obj += x[topDecompressed.size() + bot.size() + i] * dualSolutions[dominoGraph.getEdgeIndex(get<2>(zDecompressed[i]))];
    }
    qubo.setObjective(obj, GRB_MAXIMIZE);
    qubo.set(GRB_DoubleParam_TimeLimit, timeLimit);

    //0<=z is already set in definition of variable

    for (int i = 0;i < zDecompressed.size();++i) {
        GRBLinExpr sumBottom = 0;
        for (int j = 0; j < bot.size(); j++) {
            if (EdgeOrbit::topBottomToEdge(get<1>(zDecompressed[i]), bot[j]) == get<2>(zDecompressed[i])) {
                sumBottom += x[topDecompressed.size() + j];
            }
        }
        int sizeEquivClass = get<3>(zDecompressed[i]);
        int topNodeIndex = get<0>(zDecompressed[i]);

        if (dualSolutions[dominoGraph.getEdgeIndex(get<2>(zDecompressed[i]))] < 0) {
            qubo.addConstr(sumBottom<=x[topDecompressed.size()+bot.size()+i]+sizeEquivClass * (1-x[topNodeIndex]));
        }
        else if (dualSolutions[dominoGraph.getEdgeIndex(get<2>(zDecompressed[i]))] > 0) { //was ist mit = 0 kann man das ignorieren?
            qubo.addConstr(x[topDecompressed.size() + bot.size() + i] <= sizeEquivClass * x[topNodeIndex]);
            qubo.addConstr(x[topDecompressed.size() + bot.size() + i] <= sumBottom);
        }
    }
}


/*
    calculates best subbiclique with approach of edge compression of thesis
    calculates the subbicliques with the highest reduced cost and adds them to the dominoGraph.
    Return the number of added bicliques.
*/
int QuboEdgeorbits::calculateBestSubbiclique(Biclique& maxBiclique, vector<double>& dualSolutions, DominoGraph& dominoGraph, vector<double>& previousSolution, int timeLimit) {
    try{
    vector<CondensedNode> top = maxBiclique.getTop();

    vector<int> topDecompressed;
    for (CondensedNode n : top) {
        for (int i = 0;i < n.getNumOccurences();++i) {
            topDecompressed.push_back(n.getName());
        }
    }

    vector<CondensedNode> bot = maxBiclique.getBot();
    GRBEnv environment;
    environment.set("logFile", "mip2.log");
    GRBModel qubo = GRBModel(environment);
    qubo.set(GRB_DoubleParam_SoftMemLimit, 200.0);
    qubo.set(GRB_DoubleParam_MemLimit, 205.0);
    qubo.set("Symmetry", "2.0");
    ObjThresholdCallback cb;
    qubo.setCallback(&cb);
    vector<GRBVar> x;
    setUpQubo(maxBiclique, dualSolutions, dominoGraph, qubo, x,timeLimit);

    if (previousSolution.size() > 0) {
        for (int i = 0; i < x.size(); i++) {
            x[i].set(GRB_DoubleAttr_Start, previousSolution[i]);
        }
    }
    else { previousSolution = vector<double>(x.size()); }

    qubo.optimize();

    int status = qubo.get(GRB_IntAttr_Status);
    if (status == GRB_TIME_LIMIT) {
        isTimeOuted = true;
    }
    else if (status == GRB_MEM_LIMIT){
        memLimitReached = true;
    }
    try {
        upperBound = qubo.get(GRB_DoubleAttr_ObjBound);   // best possible bound
    } catch (const GRBException& e) {
        if (e.getErrorCode() != GRB_ERROR_DATA_NOT_AVAILABLE) throw;
        upperBound = GRB_INFINITY;
    }
    if(qubo.get(GRB_IntAttr_SolCount) == 0) return 0;
    lowerBound = qubo.get(GRB_DoubleAttr_ObjVal);     // best feasible column
    vector<int> solution(x.size());
    
    double optVal = qubo.get(GRB_DoubleAttr_ObjVal);
    cout << endl << endl << "optimum qubo: " << std::setprecision(10) << optVal << endl << endl;
    vector<vector<int>> columns;
    int numInsertions = 0;
    if (optVal > 1.0000001) { 
        int numSols = qubo.get(GRB_IntAttr_SolCount);
        cout << "numSols: " << numSols << endl;
        bool prevSolutionSet = false;
        for (int s = 0;s < numSols;++s) {
            qubo.set(GRB_IntParam_SolutionNumber, s);
            if (qubo.get(GRB_DoubleAttr_PoolObjVal) <= 1) {
                continue;
            }
            cout << "qubo solution value: " << qubo.get(GRB_DoubleAttr_PoolObjVal) << endl;


            for (int i = 0; i < x.size(); ++i) {
                solution[i] = static_cast<int>(x[i].get(GRB_DoubleAttr_Xn) + 0.5); //round up
                if (!prevSolutionSet) previousSolution[i] = solution[i];
            }
            prevSolutionSet = true;

            vector<CondensedNode> optTop;
            vector<CondensedNode> optBottom;
            for (int i = 0;i < topDecompressed.size();++i) {
                if (solution[i] >= 1) {
                    optTop.push_back(CondensedNode(topDecompressed[i], ceil(solution[i]), dominoGraph.getPower()));
                }
            }
            CondensedNode::condenseNodeList(optTop);
            for (int i = 0;i < bot.size();++i) {
                int solutionIndex = topDecompressed.size() + i; //shift by topElements to get correct elements from x vector
                if (solution[solutionIndex] >= 1) {
                    optBottom.push_back(CondensedNode(bot[i].getName(), ceil(solution[solutionIndex]), bot[i].getKroneckerPower()));
                }
            }
            Biclique opt = Biclique(optTop, optBottom);
            cout << "opt: " << opt.to_string() << endl;
            if (dominoGraph.insert(opt))numInsertions++;
        }
        cout << "column generation done" << endl;
        return numInsertions;
    }
    else {
        // infeasible, unbounded, or interrupt
        cout << "found no violated constraints" << endl;
        return numInsertions;
    }
    }
    catch (GRBException& e) {
        if(e.getErrorCode() == GRB_ERROR_OUT_OF_MEMORY){
            memLimitReached = true;
            return 0;
        } else{
            throw;
        }
    }
}

pair<double, double> QuboEdgeorbits::getSolutionInterval() {
    return { lowerBound,upperBound };
}

const bool QuboEdgeorbits::isTimeOut() const {
    return isTimeOuted;
}
const bool QuboEdgeorbits::reachedMemLimit() const {
    return memLimitReached;
}
